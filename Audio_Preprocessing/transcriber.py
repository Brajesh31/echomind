"""EchoMind — Speech-to-Text Transcription Service.

Wraps faster-whisper (CTranslate2) with:
- Thread-safe model caching and reuse (singleton).
- Device fallback (GPU CUDA when genuinely available -> CPU int8 fallback).
- Language detection and confidence tracking.
- Transcript normalization (whitespace collapsing, empty filtering, adjacent deduplication).
- Chunk temporal offset compensation.
- Resource cleanup in try/finally blocks.
"""

from __future__ import annotations

import logging
import os
import re
import threading
from typing import List, Optional, Tuple

from backend.config import settings
from backend.models.transcript import StructuredTranscript, TranscriptSegment

logger = logging.getLogger("echomind.transcriber")

_model: Optional[object] = None
_whisper_lock = threading.Lock()


def is_cuda_available() -> bool:
    """Check if CUDA runtime and GPU devices are genuinely available."""
    try:
        import torch
        return bool(torch.cuda.is_available() and torch.cuda.device_count() > 0)
    except Exception:
        return False


def load_model():
    """Load or return the cached WhisperModel instance in a thread-safe manner."""
    global _model
    if _model is None:
        with _whisper_lock:
            if _model is None:
                try:
                    from faster_whisper import WhisperModel
                except ImportError as exc:
                    raise RuntimeError(
                        "faster-whisper package is not installed in this environment."
                    ) from exc

                model_name = settings.whisper_model
                requested_device = settings.whisper_device
                compute_type = settings.whisper_compute_type

                # Check if requested device is CUDA but unavailable
                actual_device = requested_device
                if requested_device.lower() == "cuda" and not is_cuda_available():
                    logger.warning(
                        "CUDA device was requested but is not available on this host. Falling back to CPU."
                    )
                    actual_device = "cpu"
                    compute_type = "int8"

                logger.info(
                    "Loading Whisper model '%s' (device=%s, compute_type=%s)...",
                    model_name,
                    actual_device,
                    compute_type,
                )

                try:
                    _model = WhisperModel(
                        model_name,
                        device=actual_device,
                        compute_type=compute_type,
                    )
                except Exception as exc:
                    if actual_device != "cpu":
                        logger.warning(
                            "Failed loading Whisper on '%s' (%s). Retrying with cpu int8...",
                            actual_device,
                            exc,
                        )
                        _model = WhisperModel(
                            model_name,
                            device="cpu",
                            compute_type="int8",
                        )
                    else:
                        raise

                logger.info("Whisper model '%s' successfully loaded.", model_name)
    return _model


def normalize_segment_text(raw_text: str) -> str:
    """Normalize transcribed segment text without altering meaning.

    - Strips leading/trailing spaces.
    - Collapses repeated whitespace and tabs into single space.
    - Normalizes common unicode quotes and dashes.
    """
    if not raw_text:
        return ""
    text = raw_text.strip()
    text = re.sub(r"[\r\n\t]+", " ", text)
    text = re.sub(r" {2,}", " ", text)
    return text.strip()


def deduplicate_adjacent_segments(segments: List[TranscriptSegment]) -> List[TranscriptSegment]:
    """Filter out exact duplicate consecutive segments generated by Whisper hallucination loops."""
    if not segments:
        return []

    cleaned: List[TranscriptSegment] = []
    for seg in segments:
        if not seg.text:
            continue
        if cleaned and cleaned[-1].text.lower() == seg.text.lower():
            # If adjacent segment has identical text, extend the previous segment's end time
            cleaned[-1].end_time = max(cleaned[-1].end_time, seg.end_time)
            continue
        cleaned.append(seg)

    # Re-index segment IDs
    for idx, s in enumerate(cleaned):
        s.segment_id = idx

    return cleaned


def transcribe_chunk_whisper(
    chunk_path: str,
    time_offset: float = 0.0,
    segment_offset: int = 0,
    language: Optional[str] = None,
) -> Tuple[List[TranscriptSegment], Optional[str], float]:
    """Transcribe an audio chunk with Whisper.

    Returns:
        Tuple of (segments, detected_language, language_probability)
    """
    model = load_model()

    logger.debug("Transcribing audio chunk '%s' (offset: %.1fs)", chunk_path, time_offset)
    lang_param = None
    if language and language.lower() not in ("auto", "none"):
        lang_param = "en" if language.lower() in ("en", "english") else language.lower()

    segments_gen, info = model.transcribe(
        chunk_path,
        language=lang_param,
        beam_size=1,
        vad_filter=True,
        vad_parameters={"min_silence_duration_ms": 500},
    )

    detected_lang = getattr(info, "language", None)
    lang_prob = getattr(info, "language_probability", 1.0)

    structured_segments: List[TranscriptSegment] = []
    current_id = segment_offset

    for seg in segments_gen:
        cleaned_text = normalize_segment_text(seg.text)
        if not cleaned_text:
            continue
        start_sec = max(0.0, round(time_offset + seg.start, 2))
        end_sec = max(start_sec, round(time_offset + seg.end, 2))

        structured_segments.append(
            TranscriptSegment(
                segment_id=current_id,
                start_time=start_sec,
                end_time=end_sec,
                text=cleaned_text,
            )
        )
        current_id += 1

    return structured_segments, detected_lang, lang_prob


def transcribe_all(
    chunk_tuples: List[Tuple[str, float]],
    language: Optional[str] = None,
) -> Tuple[str, List[TranscriptSegment], str]:
    """Transcribe all audio chunks with offset compensation and normalization.

    Args:
        chunk_tuples: List of (chunk_path, duration_seconds)

    Returns:
        Tuple of (full_text, cleaned_segments, detected_language)
    """
    chunk_paths = [t[0] for t in chunk_tuples]
    all_segments: List[TranscriptSegment] = []
    detected_language = "english"
    cumulative_offset = 0.0

    try:
        current_segment_id = 0
        for i, (chunk_file, chunk_duration) in enumerate(chunk_tuples):
            chunk_segments, lang, _ = transcribe_chunk_whisper(
                chunk_path=chunk_file,
                time_offset=cumulative_offset,
                segment_offset=current_segment_id,
                language=language,
            )
            if i == 0 and lang:
                detected_language = lang

            all_segments.extend(chunk_segments)
            current_segment_id += len(chunk_segments)
            cumulative_offset += chunk_duration

        # Normalize and deduplicate adjacent identical phrases
        cleaned_segments = deduplicate_adjacent_segments(all_segments)
        full_text = " ".join(s.text for s in cleaned_segments).strip()

        logger.info(
            "Transcription complete: %d segments (%d raw), %d chars, language='%s'.",
            len(cleaned_segments),
            len(all_segments),
            len(full_text),
            detected_language,
        )
        return full_text, cleaned_segments, detected_language

    finally:
        # Guarantee removal of all audio chunk files
        for c in chunk_paths:
            if os.path.exists(c):
                try:
                    os.remove(c)
                except OSError as e:
                    logger.warning("Failed removing temporary chunk file %s: %s", c, e)